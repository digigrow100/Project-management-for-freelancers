import assert from "node:assert/strict";
import { test } from "node:test";
import { appNameOk, blockedAddress, decisionIdOk, domainOk, envNameOk, gitUrlOk, imageRefOk, resourcesOk } from "../src/validate.ts";
test("app names, domains and git URLs stay inside the allowlist", () => {
    assert.equal(appNameOk("my-site"), true);
    assert.equal(appNameOk("My-Site"), false);
    assert.equal(appNameOk("../traefik"), false);
    assert.equal(appNameOk("traefik"), false);
    assert.equal(appNameOk("a"), true);
    assert.equal(domainOk("www.example.com"), true);
    assert.equal(domainOk("example.com"), true);
    assert.equal(domainOk("localhost"), false);
    assert.equal(domainOk("bad_domain.com"), false);
    assert.equal(domainOk("app.internal"), false);
    assert.equal(gitUrlOk("https://github.com/acme/site"), true);
    assert.equal(gitUrlOk("https://user:token@github.com/acme/site"), false);
    assert.equal(gitUrlOk("http://github.com/acme/site"), false);
    assert.equal(gitUrlOk("https://127.0.0.1/acme/site"), false);
    assert.equal(gitUrlOk("https://169.254.169.254/latest"), false);
    assert.equal(imageRefOk("ghcr.io/acme/site:1.2.3"), true);
    assert.equal(imageRefOk("nginx:latest;rm"), false);
    assert.equal(envNameOk("NEXT_PUBLIC_SITE"), true);
    assert.equal(envNameOk("PATH"), false);
    assert.equal(envNameOk("LD_PRELOAD"), false);
    assert.equal(decisionIdOk("123"), true);
    assert.equal(decisionIdOk("../admin"), false);
    assert.equal(resourcesOk(1, 512), true);
    assert.equal(resourcesOk(8, 512), false);
    assert.equal(blockedAddress("10.1.1.1"), true);
    assert.equal(blockedAddress("62.171.130.156"), false);
});
